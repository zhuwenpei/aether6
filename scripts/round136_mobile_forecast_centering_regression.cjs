const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const app = fs.readFileSync(path.join(__dirname, '../src/App.tsx'), 'utf8');
const editor = fs.readFileSync(path.join(__dirname, '../src/components/ForecastIntensityCurveEditor.tsx'), 'utf8');
const css = fs.readFileSync(path.join(__dirname, '../src/index.css'), 'utf8');

const toolbar = app.match(/<div className="pro-route-toolbar[^"]+"/);
assert(toolbar, 'forecast drawing toolbar must be rendered');
assert(!toolbar[0].includes('-translate-x-1/2'), 'toolbar must not combine Tailwind v4 translate with CSS transform');
assert(app.includes('createPortal(\n          <div className="pro-route-toolbar'), 'toolbar must remain in body portal, outside map clipping');
const popup = editor.match(/"forecast-curve-popup fixed[^"]+"/);
assert(popup && !popup[0].includes('-translate-x-1/2'), 'curve popup must not combine two horizontal translations');
assert(app.includes('<ForecastIntensityCurveEditor') && app.includes('/>, document.body'), 'curve editor must stay body-portaled');
const fix = css.slice(css.lastIndexOf('/* Round136 — mobile forecast framework placement.'));
assert(fix.length > 300, 'Round136 CSS layout block missing');
assert(/\.pro-route-toolbar,\s*\.forecast-curve-popup\s*\{[^}]*translate:\s*none\s*!important;[^}]*transform:\s*translateX\(-50%\)/.test(fix), 'both panels must use exactly one centering transform');
assert(/\.forecast-curve-fullscreen\s*\{[^}]*left:\s*calc\(var\(--aether-vv-left,\s*0px\)\s*\+\s*8px\)[^}]*width:\s*calc\(var\(--aether-vvw,\s*100vw\)\s*-\s*16px\)[^}]*translate:\s*none\s*!important;[^}]*transform:\s*none\s*!important;/.test(fix), 'fullscreen must use viewport inset without translate');
assert(css.includes('left: calc(var(--aether-vv-left, 0px) + var(--aether-vvw, 100vw) / 2) !important'), 'phone layout must anchor to visual viewport center');
assert(css.includes('max-width: calc(var(--aether-vvw, 100vw) - 16px'), 'mobile toolbar must not be wider than visible viewport');
assert(css.includes('width: min(960px, calc(var(--aether-vvw, 100vw) - 16px))'), 'normal curve editor must fit visible viewport');
console.log('ROUND136 mobile forecast toolbar + intensity curve single-translate viewport centering: PASS');
